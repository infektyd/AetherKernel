// ---------------------------------------------------------------------------
// State (set by kernel_vc_console_selftest, read by accessors)
// ---------------------------------------------------------------------------
static int          console_ok_val     = 0;
static unsigned int console_rows_val   = 0;
static unsigned int console_cols_val   = 0;
static unsigned int console_glyphs_val = 0;

// ---------------------------------------------------------------------------
// Internal: write one 8x8 glyph at (col, row) in character-cell coordinates.
// ---------------------------------------------------------------------------
static void blit_char(unsigned int col, unsigned int row, unsigned char c,
                      uint32_t fg, uint32_t bg)
{
    if (c < 0x20U || c > 0x7EU) c = 0x20U;
    const uint8_t *glyph = font8x8[c - 0x20U];

    unsigned long fb_addr  = kernel_vc_mbox_fb_addr();
    uint32_t      pitch    = (uint32_t)kernel_vc_mbox_fb_pitch();
    uint32_t      fb_w     = (uint32_t)kernel_vc_mbox_fb_width();
    uint32_t      fb_h     = (uint32_t)kernel_vc_mbox_fb_height();

    uint32_t px = col * 8U;
    uint32_t py = row * 8U;
    if (px + 8U > fb_w || py + 8U > fb_h) return;

    volatile uint32_t *fb = (volatile uint32_t *)(unsigned long)fb_addr;
    uint32_t stride = pitch / 4U; /* pixels per row */

    for (unsigned int y = 0U; y < 8U; y++) {
        uint8_t bits = glyph[y];
        for (unsigned int x = 0U; x < 8U; x++) {
            uint32_t pixel  = (bits & (0x80U >> x)) ? fg : bg;
            fb[(py + y) * stride + (px + x)] = pixel;
        }
    }
}

// ---------------------------------------------------------------------------
// Public: blit "AetherKernel v60" banner and verify readback of first glyph.
// Returns 1 on success, 0 on failure (no framebuffer or readback mismatch).
// ---------------------------------------------------------------------------
int kernel_vc_console_selftest(void)
{
    unsigned long fb_addr = kernel_vc_mbox_fb_addr();
    uint32_t      fb_w    = (uint32_t)kernel_vc_mbox_fb_width();
    uint32_t      fb_h    = (uint32_t)kernel_vc_mbox_fb_height();
    uint32_t      pitch   = (uint32_t)kernel_vc_mbox_fb_pitch();

    if (fb_addr == 0UL || fb_w == 0U || fb_h == 0U || pitch == 0U) {
        console_ok_val     = 0;
        console_rows_val   = 0;
        console_cols_val   = 0;
        console_glyphs_val = 0;
        return 0;
    }

    console_cols_val = fb_w / 8U;
    console_rows_val = fb_h / 8U;

    /* Blit "AetherKernel v60" at row 0, starting at col 0. */
    static const char banner[] = "AetherKernel v60";
    uint32_t fg = 0xFFFFFFFFU;  /* white  */
    uint32_t bg = 0x00000000U;  /* black  */

    unsigned int col = 0U;
    for (const char *p = banner; *p && col < console_cols_val; p++, col++) {
        blit_char(col, 0U, (unsigned char)*p, fg, bg);
    }
    console_glyphs_val = col;

    /* Readback: verify pixels written for the first glyph ('A' at col 0). */
    volatile uint32_t *fb     = (volatile uint32_t *)(unsigned long)fb_addr;
    uint32_t           stride = pitch / 4U;
    const uint8_t     *glyph  = font8x8['A' - 0x20U];
    int                bad    = 0;

    for (unsigned int y = 0U; y < 8U && !bad; y++) {
        uint8_t bits = glyph[y];
        for (unsigned int x = 0U; x < 8U && !bad; x++) {
            uint32_t expected = (bits & (0x80U >> x)) ? fg : bg;
            uint32_t actual   = fb[y * stride + x];
            if (actual != expected) bad = 1;
        }
    }

    console_ok_val = bad ? 0 : 1;
    return console_ok_val;
}

int          kernel_vc_console_ok(void)     { return console_ok_val;     }
unsigned int kernel_vc_console_rows(void)   { return console_rows_val;   }
unsigned int kernel_vc_console_cols(void)   { return console_cols_val;   }
unsigned int kernel_vc_console_glyphs(void) { return console_glyphs_val; }
